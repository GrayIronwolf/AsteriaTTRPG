// Refresh NAC fields in checked-in indexes without rebuilding unrelated content.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const races=new Map();
for(const dir of fs.readdirSync(path.join(root,'content/races'),{withFileTypes:true})){
 if(!dir.isDirectory())continue;
 const file=path.join(root,'content/races',dir.name,'index.md');if(!fs.existsSync(file))continue;
 const text=fs.readFileSync(file,'utf8');
 races.set(dir.name,{naturalAC:Number(text.match(/^naturalAC:\s*(\d+)/m)?.[1]||1),naturalACSource:text.match(/^naturalACSource:\s*(\S+)/m)?.[1]||'fallback'});
}
const updateHeader=(text,fields)=>text.replace(/^(naturalAC:.*)$/m,`naturalAC: ${fields.naturalAC}`).replace(/^(naturalAC:.*\r?\n)(?:naturalACSource:.*\r?\n)?/m,`$1naturalACSource: ${fields.naturalACSource}\n`);
const file=path.join(root,'data/universal-compendium-index.json');const index=JSON.parse(fs.readFileSync(file,'utf8'));
for(const entry of index.entries){const fields=entry.domain==='race'?races.get(entry.slug):null;if(fields){for(const name of Object.keys(entry.metadata))if(['naturalac','naturalacsource'].includes(name.toLowerCase().replace(/[^a-z0-9]/g,'')))delete entry.metadata[name];Object.assign(entry.metadata,fields);if(entry.body)entry.body=updateHeader(entry.body,fields);}}
fs.writeFileSync(file,JSON.stringify(index,null,2));
fs.writeFileSync(path.join(root,'js/universal-compendium-index.js'),`/* Generated by scripts/generate-universal-compendium-index.js. Do not edit directly. */\n(function(){\n  window.ASTERIA_UNIVERSAL_COMPENDIUM_INDEX = ${JSON.stringify(index,null,2)};\n})();\n`);
const manifestPath=path.join(root,'js/content-manifest.js');const context={window:{}};vm.runInNewContext(fs.readFileSync(manifestPath,'utf8'),context);
for(const page of context.window.ASTERIA_CONTENT.pages){const fields=page.category.toLowerCase().startsWith('races/')?races.get(page.slug):null;if(fields)page.content=updateHeader(page.content,fields);}
fs.writeFileSync(manifestPath,`window.ASTERIA_CONTENT = ${JSON.stringify(context.window.ASTERIA_CONTENT,null,2)};\n`);
console.log(`Synchronized NAC metadata for ${races.size} races.`);
